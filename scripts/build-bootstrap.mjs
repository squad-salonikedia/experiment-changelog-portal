/**
 * Builds supabase/bootstrap-dev.sql — schema plus every migration, in order, as
 * one paste.
 *
 *   node scripts/build-bootstrap.mjs
 *
 * Setting up a fresh database otherwise means running nine files by hand in the
 * right order, which is exactly the sort of thing that gets done half-way. Two
 * things are fixed up on the way through:
 *
 *   - schema.sql creates its tables unconditionally, so re-running it fails.
 *     The bootstrap rewrites those to "if not exists" — someone re-pasting it
 *     should get a no-op, not an error.
 *   - allowed_users, which gates who can sign in, has never been in schema.sql.
 *     Its definition only lived inside scripts/setup-access-table.mjs, so a new
 *     project built from the schema alone would let nobody in.
 *
 * Re-run this after adding a migration.
 */
import { readFileSync, writeFileSync, readdirSync } from "fs";
import path from "path";
import { fileURLToPath } from "url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const read = (p) => readFileSync(path.join(root, p), "utf8").trimEnd();

const idempotent = (sql) =>
  sql
    .replace(/^create table (?!if not exists)/gim, "create table if not exists ")
    .replace(/^create index (?!if not exists)/gim, "create index if not exists ")
    .replace(/^create unique index (?!if not exists)/gim, "create unique index if not exists ");

const ALLOWED_USERS = `-- Who is allowed to sign in. Every request is checked against this table, so a
-- database without it lets nobody in — including you.
create table if not exists allowed_users (
  id uuid primary key default gen_random_uuid(),
  email text unique not null,
  role text default 'member' check (role in ('admin', 'member')),
  name text,
  invited_by text,
  created_at timestamptz default now()
);

-- Add yourself before signing in, or run scripts/seed-dev.mjs which does it for
-- you along with some example experiments:
--   insert into allowed_users (email, role, name)
--   values ('you@squadstack.ai', 'admin', 'Your Name')
--   on conflict (email) do nothing;`;

const migrations = readdirSync(path.join(root, "supabase/migrations"))
  .filter((f) => f.endsWith(".sql"))
  .sort();

const section = (title, body) =>
  `\n\n-- ===========================================================\n` +
  `-- ${title}\n` +
  `-- ===========================================================\n\n${body}\n`;

let out = `-- Flywheel — one-shot bootstrap for a fresh database.
--
-- Paste the whole file into Supabase -> SQL Editor -> New query -> Run. It is
-- the schema, the access table and every migration in order, so a new project
-- lands exactly where production is in a single paste.
--
-- Safe to re-run: every statement either checks for existence first or is a
-- no-op the second time.
--
-- Generated by scripts/build-bootstrap.mjs — do not edit by hand.`;

out += section("schema.sql", idempotent(read("supabase/schema.sql")));
out += section("allowed_users (not in schema.sql — see build-bootstrap.mjs)", ALLOWED_USERS);
for (const file of migrations) {
  out += section(`migrations/${file}`, idempotent(read(`supabase/migrations/${file}`)));
}

writeFileSync(path.join(root, "supabase/bootstrap-dev.sql"), out + "\n");
console.log(`Wrote supabase/bootstrap-dev.sql — schema + allowed_users + ${migrations.length} migrations.`);
